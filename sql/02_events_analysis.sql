-- الهدف: تحليل أحداث المباراة (أهداف، بطاقات، ...) الخاصة
--        بمنتخب السعودية، بالإضافة إلى عدد الأهداف التي
--        استقبلها المنتخب من الخصوم في مبارياته الثلاث
--        (match_id: 15, 39, 64)
-- المصدر: جدول match_events
-- ============================================================

USE worldcup;

-- الجزء الأول: كل الأحداث التي قام بها منتخب السعودية
-- (أهداف سجّلها، بطاقات حصل عليها، ركنيات نفذها ... إلخ)
SELECT 
    'Saudi Arabia' AS team, 
    event_type, 
    COUNT(event_type) AS total  
FROM match_events 
WHERE team_id = 31 
GROUP BY event_type

UNION ALL

-- الجزء الثاني: الأهداف التي استقبلها منتخب السعودية
-- (نحسبها بحساب أهداف الفريق المنافس في نفس المباريات
--  التي لعبتها السعودية)
SELECT 
    'Saudi Arabia' AS team,
    'Goals Conceded' AS event_type,
    COUNT(event_type) AS total
FROM match_events 
WHERE match_id IN (15, 39, 64) 
    AND team_id != 31 
    AND event_type = 'Goal';

